import { app } from 'electron'
import { join } from 'path'
import Database from 'better-sqlite3'
import { drizzle, BetterSQLite3Database } from 'drizzle-orm/better-sqlite3'
import { migrate } from 'drizzle-orm/better-sqlite3/migrator'
import { is } from '@electron-toolkit/utils'
import * as schema from './schema'

export type AppDatabase = BetterSQLite3Database<typeof schema>

class DatabaseClient {
  private static instance: DatabaseClient | null = null
  public sqlite: Database.Database | null = null
  public db: AppDatabase | null = null

  private constructor() {}

  public static getInstance(): DatabaseClient {
    if (!DatabaseClient.instance) {
      DatabaseClient.instance = new DatabaseClient()
    }
    return DatabaseClient.instance
  }

  public init(customPath?: string): AppDatabase {
    if (this.db) {
      return this.db
    }

    const dbPath = customPath || this.getDefaultDbPath()
    this.sqlite = new Database(dbPath)

    // Performance and safety pragmas
    this.sqlite.pragma('journal_mode = WAL')
    this.sqlite.pragma('foreign_keys = ON')

    this.db = drizzle(this.sqlite, { schema })

    // Apply pending migrations generated by drizzle-kit (schema.ts is the source of truth)
    migrate(this.db, { migrationsFolder: this.getMigrationsFolder() })

    return this.db
  }

  private getDefaultDbPath(): string {
    if (is.dev) return join(process.cwd(), 'masarat.db')
    return join(app.getPath('userData'), 'masarat.db')
  }

  private getMigrationsFolder(): string {
    if (is.dev) return join(process.cwd(), 'drizzle')
    return join(process.resourcesPath, 'drizzle')
  }

  public getDb(): AppDatabase {
    if (!this.db) {
      return this.init()
    }
    return this.db
  }

  public close(): void {
    if (this.sqlite) {
      this.sqlite.close()
      this.sqlite = null
      this.db = null
    }
  }
}

// Client singleton exports
export const dbClient = DatabaseClient.getInstance()
export const getDb = (): AppDatabase => dbClient.getDb()
export const initDb = (path?: string): AppDatabase => dbClient.init(path)
export const closeDb = (): void => dbClient.close()

// Direct db accessor proxy
export const db = new Proxy({} as AppDatabase, {
  get(_target, prop) {
    const activeDb = getDb()
    const value = Reflect.get(activeDb, prop)
    return typeof value === 'function' ? value.bind(activeDb) : value
  }
})

export { schema }
