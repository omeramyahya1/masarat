import Database from 'better-sqlite3'
import { drizzle, BetterSQLite3Database } from 'drizzle-orm/better-sqlite3'
import { migrate } from 'drizzle-orm/better-sqlite3/migrator'
import * as schema from './schema'
import { config } from '../config'

export type AppDatabase = BetterSQLite3Database<typeof schema>

class DatabaseClient {
  private static instance: DatabaseClient | null = null
  public sqlite: Database.Database | null = null
  public db: AppDatabase | null = null

  // Private so the only instance is getInstance()'s
  // eslint-disable-next-line @typescript-eslint/no-empty-function
  private constructor() {}

  public static getInstance(): DatabaseClient {
    if (!DatabaseClient.instance) {
      DatabaseClient.instance = new DatabaseClient()
    }
    return DatabaseClient.instance
  }

  public init(customPath?: string): AppDatabase {
    if (this.db) {
      return this.db
    }

    const dbPath = customPath || this.getDefaultDbPath()
    const sqlite = new Database(dbPath)

    // Only publish the connection once migrations succeed, so a failed init can be retried
    try {
      // Performance and safety pragmas
      sqlite.pragma('journal_mode = WAL')

      const db = drizzle(sqlite, { schema })

      // Apply pending migrations generated by drizzle-kit (schema.ts is the source of truth).
      // Foreign keys are off while they run: rebuilding a referenced table (drizzle's way of
      // changing a CHECK) would fail otherwise, and the PRAGMA can't change inside the
      // migration's transaction. The check afterwards makes sure nothing was left dangling.
      sqlite.pragma('foreign_keys = OFF')
      migrate(db, { migrationsFolder: this.getMigrationsFolder() })
      if ((sqlite.pragma('foreign_key_check') as unknown[]).length > 0) {
        throw new Error('Migration left foreign key violations')
      }
      sqlite.pragma('foreign_keys = ON')

      this.sqlite = sqlite
      this.db = db
      return db
    } catch (err) {
      sqlite.close()
      throw err
    }
  }

  // TODO(web): the driver is still better-sqlite3, which Bun can't load. The database
  // (bun:sqlite or Postgres) is decided in the production brainstorm.
  private getDefaultDbPath(): string {
    return config.databasePath
  }

  private getMigrationsFolder(): string {
    return config.migrationsFolder
  }

  public getDb(): AppDatabase {
    if (!this.db) {
      return this.init()
    }
    return this.db
  }

  public close(): void {
    if (this.sqlite) {
      this.sqlite.close()
      this.sqlite = null
      this.db = null
    }
  }
}

// Client singleton exports
export const dbClient = DatabaseClient.getInstance()
export const getDb = (): AppDatabase => dbClient.getDb()
export const initDb = (path?: string): AppDatabase => dbClient.init(path)
export const closeDb = (): void => dbClient.close()

// Direct db accessor proxy
export const db = new Proxy({} as AppDatabase, {
  get(_target, prop) {
    const activeDb = getDb()
    const value = Reflect.get(activeDb, prop)
    return typeof value === 'function' ? value.bind(activeDb) : value
  }
})

export { schema }
